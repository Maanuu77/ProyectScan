"""The zip the user downloads: the documentation set plus two short guides."""

import zipfile
from pathlib import Path

from repo_xray.export.markdown import FOLDER, Bundle, build_documents
from repo_xray.export.png import add_png_copies
from repo_xray.pipeline import Analysis

HOW_TO_USE = """\
# How to use these files

This zip was generated by repo-xray from the source code of **{name}**.

## Quick start

1. Copy the `architecture` folder into your repository, inside a `docs` folder:
   `docs/architecture/`.
2. Open `README-snippet.md`, copy its content and paste it into your project's
   `README.md`, wherever you want the architecture to appear.
3. Commit and push. GitHub shows the diagrams in light or dark mode,
   matching each reader's theme.

## What is inside

| Path | What it is |
| --- | --- |
| `architecture/README.md` | The main page: summary, overview, features and key flows |
| `architecture/features/` | One page per feature, with its endpoints, connections and flows |
| `architecture/images/` | Every diagram as SVG, in a light and a dark version |
| `architecture/png/` | The same diagrams as PNG, for slides, posts or documents |
| `architecture/analysis.json` | The raw analysis, in case you want to build something else |

## Keeping it up to date

The documents describe the code as it was when they were generated. Run
repo-xray again after big changes and replace the `architecture` folder.
"""

SNIPPET = """\
## Architecture

{summary}

<picture>
  <source media="(prefers-color-scheme: dark)" srcset="docs/architecture/images/overview-dark.svg">
  <img alt="{name} architecture overview" src="docs/architecture/images/overview-light.svg">
</picture>

More detail, feature by feature and request by request, in
[docs/architecture](docs/architecture/README.md).
"""


def build_bundle(analysis: Analysis, png: bool = True) -> Bundle:
    bundle = build_documents(analysis)
    if png:
        add_png_copies(bundle)
    name = analysis.stack.name
    index = str(bundle[f"{FOLDER}/README.md"])
    summary = index.split("\n\n")[1] if index.count("\n\n") > 1 else ""
    bundle["HOW-TO-USE.md"] = HOW_TO_USE.format(name=name)
    bundle["README-snippet.md"] = SNIPPET.format(name=name, summary=summary)
    return bundle


def write_zip(bundle: Bundle, destination: Path) -> Path:
    destination.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(destination, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for path in sorted(bundle):
            content = bundle[path]
            archive.writestr(path, content.encode("utf-8") if isinstance(content, str) else content)
    return destination
